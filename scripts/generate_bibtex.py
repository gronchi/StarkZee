"""Generate docs/references.bib from the audited bibliography registry.

``starkzee/data/bibliography.json`` is the single source of truth.  Both the
Sphinx manual (sphinxcontrib-bibtex) and ``docs/manual.tex`` (biblatex) read
the generated file, so never edit ``docs/references.bib`` by hand::

    python scripts/generate_bibtex.py           # rewrite the .bib
    python scripts/generate_bibtex.py --check   # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = ROOT / "starkzee" / "data" / "bibliography.json"
BIB_PATH = ROOT / "docs" / "references.bib"

# Container names that are publishers rather than journals.
BOOKS = {"bethe_salpeter1957", "edmonds1957", "griem1997"}
# Collective authors must be braced so BibTeX does not split them into
# first/last names.
COLLECTIVE_AUTHORS = {"JET Contributors", "NIST ASD Team"}


def _author(name: str) -> str:
    return "{" + name + "}" if name in COLLECTIVE_AUTHORS else name


def _fields(work: dict) -> tuple[str, list[tuple[str, str]]]:
    authors = " and ".join(_author(a) for a in work["authors"])
    if work["id"] in BOOKS:
        entry_type = "book"
        # Double braces keep the registry's capitalization in every style.
        fields = [("author", authors), ("title", "{" + work["title"] + "}"),
                  ("publisher", work["container"])]
    elif "version" in work:
        entry_type = "misc"
        title = f"{work['title']} (ver. {work['version']})"
        fields = [("author", authors), ("title", "{" + title + "}"),
                  ("howpublished", work["container"])]
    else:
        entry_type = "article"
        fields = [("author", authors), ("title", "{" + work["title"] + "}"),
                  ("journal", work["container"])]
        if "volume" in work:
            fields.append(("volume", work["volume"]))
        if "issue" in work:
            fields.append(("number", work["issue"]))
        if "pages" in work:
            fields.append(("pages", work["pages"].replace("-", "--")))
        elif "article_number" in work:
            fields.append(("pages", work["article_number"]))
    fields.append(("year", str(work["year"])))
    fields.append(("doi", work["doi"]))
    if "locator_note" in work:
        fields.append(("note", work["locator_note"].replace("&", r"\&")))
    return entry_type, fields


def render(registry: dict) -> str:
    lines = [
        "% Generated by scripts/generate_bibtex.py from",
        "% starkzee/data/bibliography.json.  Do not edit by hand.",
        "",
    ]
    for work in registry["works"]:
        entry_type, fields = _fields(work)
        lines.append(f"@{entry_type}{{{work['citation_key']},")
        lines.extend(f"  {name} = {{{value}}}," for name, value in fields)
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if docs/references.bib is out of date")
    args = parser.parse_args()
    registry = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    text = render(registry)
    if args.check:
        current = BIB_PATH.read_text(encoding="utf-8") if BIB_PATH.exists() else ""
        if current != text:
            print(f"{BIB_PATH} is stale; run scripts/generate_bibtex.py")
            return 1
        return 0
    BIB_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {BIB_PATH.relative_to(ROOT)} ({len(registry['works'])} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
